"""
performance_reader.py — PersonaVid performance feedback loop.

Reads Instagram/TikTok engagement data for videos generated by PersonaVid,
extracts lessons about what works (shot types, product angles, caption styles),
and writes them back to intelligence/personavid_brain.md learned section.

The shot director reads the brain on the next run — so every video that
performs well teaches the system how to make the next one better.

Usage:
    python3 performance_reader.py           # analyze all tracked posts
    python3 performance_reader.py --dry-run # show analysis without writing lessons
"""

import json
import sys
import os
import argparse
import requests
import anthropic
from datetime import datetime, timezone, timedelta
from pathlib import Path

ROOT = Path(__file__).parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT.parent / "shopify_store"))

from dotenv import load_dotenv
load_dotenv(ROOT / ".env")
load_dotenv(ROOT.parent / "shopify_store" / ".env")

client = anthropic.Anthropic()

PERFORMANCE_LOG = ROOT / "logs" / "performance_log.json"
BRAIN_PATH      = ROOT / "intelligence" / "personavid_brain.md"
LEARNED_PATH    = ROOT / "intelligence" / "personavid_brain.learned.md"

FB_TOKEN      = os.getenv("INSTAGRAM_ACCESS_TOKEN")
FB_PAGE_ID    = "1100977816423126"
IG_ACCOUNT_ID = "17841439250634195"


# ── Instagram API ─────────────────────────────────────────────────────────────

def _page_token() -> str:
    r = requests.get(
        f"https://graph.facebook.com/{FB_PAGE_ID}",
        params={"access_token": FB_TOKEN, "fields": "access_token"},
        timeout=10
    )
    return r.json().get("access_token", FB_TOKEN)


def fetch_ig_media(limit: int = 50) -> list[dict]:
    page_token = _page_token()
    r = requests.get(
        f"https://graph.facebook.com/{IG_ACCOUNT_ID}/media",
        params={
            "access_token": page_token,
            "fields": "id,timestamp,like_count,comments_count,media_type,caption",
            "limit": limit,
        },
        timeout=15
    )
    posts = r.json().get("data", [])

    # Enrich with reach
    enriched = []
    cutoff = datetime.now(timezone.utc) - timedelta(days=90)
    for p in posts:
        try:
            ts = datetime.fromisoformat(p.get("timestamp", "").replace("Z", "+00:00"))
            if ts < cutoff:
                continue
        except Exception:
            pass
        try:
            ir = requests.get(
                f"https://graph.facebook.com/{p['id']}/insights",
                params={"metric": "reach,saved", "access_token": page_token},
                timeout=10
            )
            for item in ir.json().get("data", []):
                vals = item.get("values", [])
                p[item["name"]] = vals[0]["value"] if vals else 0
        except Exception:
            p["reach"] = 0
            p["saved"] = 0
        enriched.append(p)
    return enriched


# ── Performance log ───────────────────────────────────────────────────────────

def load_performance_log() -> dict:
    if PERFORMANCE_LOG.exists():
        try:
            return json.loads(PERFORMANCE_LOG.read_text())
        except Exception:
            pass
    return {"posts": [], "lessons": []}


def save_performance_log(data: dict):
    PERFORMANCE_LOG.parent.mkdir(exist_ok=True)
    PERFORMANCE_LOG.write_text(json.dumps(data, indent=2))


def tag_post_as_personavid(post_id: str, metadata: dict):
    """
    Call this from the PersonaVid pipeline when a video is posted.
    Tags the post so performance_reader knows it was generated by PersonaVid.

    metadata should include:
        product_title, shot_types, subject (carter/cash), prompt_style
    """
    log = load_performance_log()
    log["posts"].append({
        "post_id":     post_id,
        "platform":    "instagram",
        "tagged_at":   datetime.now().isoformat(),
        "source":      "personavid",
        **metadata
    })
    save_performance_log(log)


# ── Analysis ──────────────────────────────────────────────────────────────────

def analyze_performance(ig_posts: list[dict], tracked_posts: list[dict]) -> list[str]:
    """
    Compare PersonaVid posts vs non-PersonaVid posts.
    Extract lessons about what shot types / captions / subjects perform best.
    """
    # Cross-reference tracked posts with live IG data
    tracked_ids = {p["post_id"] for p in tracked_posts}
    pv_posts   = [p for p in ig_posts if p["id"] in tracked_ids]
    other_posts = [p for p in ig_posts if p["id"] not in tracked_ids]

    if not pv_posts:
        # No PersonaVid posts yet — analyze all video posts for patterns
        video_posts = [p for p in ig_posts if p.get("media_type") == "VIDEO"]
        if not video_posts:
            return []
        pv_posts = video_posts
        print(f"  No PersonaVid-tagged posts yet — analyzing all {len(video_posts)} video posts")
    else:
        print(f"  PersonaVid posts: {len(pv_posts)}  |  Other posts: {len(other_posts)}")

    # Build context for Claude
    pv_summary = [
        {
            "post_id":    p.get("id"),
            "reach":      p.get("reach", 0),
            "likes":      p.get("like_count", 0),
            "saved":      p.get("saved", 0),
            "media_type": p.get("media_type"),
            "caption":    (p.get("caption") or "")[:200],
            # Metadata from our log if available
            "product":    next((t.get("product_title", "") for t in tracked_posts if t.get("post_id") == p.get("id")), ""),
            "shot_types": next((t.get("shot_types", []) for t in tracked_posts if t.get("post_id") == p.get("id")), []),
            "subject":    next((t.get("subject", "") for t in tracked_posts if t.get("post_id") == p.get("id")), ""),
        }
        for p in sorted(pv_posts, key=lambda x: x.get("reach", 0), reverse=True)
    ]

    prompt = f"""You are the performance analyst for PersonaVid — an AI video generator for Continuum Goods.
Your job: read real Instagram performance data from our generated videos and extract specific lessons
that will help the shot director make better decisions on the next video.

VIDEO PERFORMANCE DATA:
{json.dumps(pv_summary, indent=2)}

Based ONLY on what this data shows, write 3-5 specific lessons for the shot director.
Focus on:
- Which caption styles drive reach vs saves vs likes
- What subjects (carter/cash) or behaviors get the most engagement
- What product categories perform best in video
- What the data implies about optimal video length or format
- Any patterns in captions of top-performing posts

If the data is too sparse (fewer than 5 posts), say so and give only 1-2 tentative observations.

Return a plain list of lessons, one per line, starting with "-":
- [lesson]
- [lesson]
...

Be specific. No generic advice."""

    response = client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=400,
        messages=[{"role": "user", "content": prompt}]
    ).content[0].text.strip()

    lessons = []
    for line in response.splitlines():
        line = line.strip()
        if line.startswith("- "):
            lesson = line[2:].strip()
            if len(lesson) > 20:
                lessons.append(lesson)
    return lessons


# ── Brain writer ──────────────────────────────────────────────────────────────

def write_lessons(lessons: list[str], dry_run: bool = False):
    if not lessons:
        return
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    entry = f"\n## {now} — performance_reader\n"
    for lesson in lessons:
        entry += f"- {lesson}\n"

    if dry_run:
        print("\n  [DRY RUN] Would write to personavid_brain.learned.md:")
        print(entry)
        return

    if not LEARNED_PATH.exists():
        LEARNED_PATH.write_text(
            "# Learned Rules — PersonaVid\n\n"
            "> Auto-appended by performance_reader.py from real post performance.\n"
            + entry
        )
    else:
        with LEARNED_PATH.open("a") as f:
            f.write(entry)
    print(f"  Wrote {len(lessons)} lesson(s) to personavid_brain.learned.md")


# ── Main ──────────────────────────────────────────────────────────────────────

def run(dry_run: bool = False):
    print("=" * 56)
    print("  PersonaVid — Performance Reader")
    print(f"  {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    print("=" * 56)

    if not FB_TOKEN:
        print("  INSTAGRAM_ACCESS_TOKEN not set — cannot pull insights")
        return

    print("\n  Pulling Instagram performance data...")
    ig_posts = fetch_ig_media()
    print(f"  Found {len(ig_posts)} recent posts with insights")

    log = load_performance_log()
    tracked = log.get("posts", [])
    print(f"  PersonaVid-tagged posts in log: {len(tracked)}")

    print("\n  Analyzing what works...")
    lessons = analyze_performance(ig_posts, tracked)

    if lessons:
        print(f"\n  {len(lessons)} lesson(s) extracted:")
        for l in lessons:
            print(f"    - {l[:90]}")
        write_lessons(lessons, dry_run=dry_run)
    else:
        print("  Not enough data for lessons yet — keep posting")

    # Save run to log
    log["last_run"] = datetime.now().isoformat()
    log["lessons"] = log.get("lessons", []) + [
        {"date": datetime.now().isoformat(), "lesson": l} for l in lessons
    ]
    if not dry_run:
        save_performance_log(log)

    print(f"\n  Log → {PERFORMANCE_LOG}")
    print("=" * 56)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    run(dry_run=args.dry_run)
